export function translate(language: Language, text: string, values: Record<string, string | number> = {}): string {
  const column = { 'zh-hans': 0, 'zh-hant': 1, ja: 2 } as const;
  const translated = language === 'en' ? text : messages[text]?.[column[language]] || text;
  return translated.replace(/\{(\w+)\}/g, (match, key: string) => values[key] == null ? match : String(values[key]));
}
